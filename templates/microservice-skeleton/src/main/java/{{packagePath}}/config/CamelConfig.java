import org.apache.camel.CamelContext;
import org.apache.camel.component.http.HttpComponent;
import org.apache.camel.component.jackson.JacksonDataFormat;
import org.apache.camel.spi.RestConfiguration;
import org.apache.camel.spring.boot.CamelContextConfiguration;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * Apache Camel Configuration for {{serviceNameTitleCase}}
 *
 * Configures Camel context, routes, components, and integration patterns.
 * Optimized for enterprise reliability and performance.
 * Generated by Enterprise CLI - customize according to your integration requirements.
 */
@Configuration
public class CamelConfig {

    @Value("${camel.component.http.connection-timeout:30000}")
    private int httpConnectionTimeout;

    @Value("${camel.component.http.socket-timeout:30000}")
    private int httpSocketTimeout;

    @Value("${server.port:8080}")
    private int serverPort;

    /**
     * Camel Context Configuration
     */
    @Bean
    public CamelContextConfiguration camelContextConfiguration() {
        return new CamelContextConfiguration() {
            @Override
            public void beforeApplicationStart(CamelContext camelContext) {
                // Global error handling configuration
                // Note: Error handling is now configured per route in Camel 4.x

                // Performance optimizations
                camelContext.getGlobalOptions().put("CamelJacksonEnableTypeConverter", "true");
                camelContext.getGlobalOptions().put("CamelJacksonTypeConverterToPojo", "true");

                // Monitoring and management
                camelContext.setUseMDCLogging(true);
                camelContext.setUseBreadcrumb(true);
                camelContext.setMessageHistory(true);

                // Security settings
                camelContext.getGlobalOptions().put("CamelHttpSkipRequestHeaders", "Authorization,Cookie");
                camelContext.getGlobalOptions().put("CamelHttpSkipResponseHeaders", "Set-Cookie");
            }

            @Override
            public void afterApplicationStart(CamelContext camelContext) {
                // Post-startup configurations if needed
            }
        };
    }

    /**
     * HTTP Component Configuration
     */
    @Bean
    public HttpComponent httpComponent() {
        HttpComponent httpComponent = new HttpComponent();

        // Connection settings
        httpComponent.setConnectionTimeToLive(300000); // 5 minutes
        httpComponent.setConnectionsPerRoute(20);
        httpComponent.setMaxTotalConnections(200);

        // Timeout settings - configured via component properties in Camel 4.x
        // httpComponent.setConnectionTimeout() is deprecated

        // Security settings - configured via application properties in Camel 4.x
        // httpComponent.setSkipRequestHeaders() and setSkipResponseHeaders() deprecated

        return httpComponent;
    }

    /**
     * Jackson Data Format for JSON processing
     */
    @Bean
    public JacksonDataFormat jacksonDataFormat() {
        JacksonDataFormat jacksonDataFormat = new JacksonDataFormat();

        // JSON processing settings
        jacksonDataFormat.setPrettyPrint(false);
        jacksonDataFormat.setInclude("NON_NULL");
        jacksonDataFormat.setDisableFeatures("FAIL_ON_UNKNOWN_PROPERTIES,FAIL_ON_EMPTY_BEANS");
        jacksonDataFormat.setEnableFeatures("ACCEPT_EMPTY_STRING_AS_NULL_OBJECT");

        // Type safety
        jacksonDataFormat.setAllowUnmarshallType(true);

        return jacksonDataFormat;
    }

    /**
     * REST Configuration for Camel REST DSL
     */
    @Bean
    public RestConfiguration restConfiguration() {
        RestConfiguration restConfiguration = new RestConfiguration();

        // Component configuration
        restConfiguration.setComponent("servlet");
        restConfiguration.setPort(serverPort);
        restConfiguration.setContextPath("/api/v1/camel");

        // JSON binding
        restConfiguration.setBindingMode(org.apache.camel.spi.RestConfiguration.RestBindingMode.json);
        // Data format properties are now configured via Jackson DataFormat

        // API documentation
        restConfiguration.setApiContextPath("/api-doc");
        // API properties are now configured via OpenAPI specification

        // CORS settings
        restConfiguration.setEnableCORS(true);
        // CORS credentials configuration moved to application properties

        // Error handling
        restConfiguration.setSkipBindingOnErrorCode(false);

        return restConfiguration;
    }

    /**
     * Custom route policy for monitoring and management
     */
    @Bean
    public org.apache.camel.spi.RoutePolicy customRoutePolicy() {
        return new org.apache.camel.support.RoutePolicySupport() {
            @Override
            public void onStart(org.apache.camel.Route route) {
                super.onStart(route);
                // Custom logic when route starts
                System.out.println("Route started: " + route.getId());
            }

            @Override
            public void onStop(org.apache.camel.Route route) {
                super.onStop(route);
                // Custom logic when route stops
                System.out.println("Route stopped: " + route.getId());
            }

            @Override
            public void onExchangeBegin(org.apache.camel.Route route, org.apache.camel.Exchange exchange) {
                // Add custom headers or properties
                exchange.setProperty("routeStartTime", System.currentTimeMillis());
            }

            @Override
            public void onExchangeDone(org.apache.camel.Route route, org.apache.camel.Exchange exchange) {
                // Log processing time
                Long startTime = exchange.getProperty("routeStartTime", Long.class);
                if (startTime != null) {
                    long processingTime = System.currentTimeMillis() - startTime;
                    if (processingTime > 1000) { // Log slow routes
                        System.out.println("Slow route detected: " + route.getId() + " took " + processingTime + "ms");
                    }
                }
            }
        };
    }

    /**
     * Camel health check configuration
     */
    @Bean
    public org.apache.camel.health.HealthCheckRegistry healthCheckRegistry() {
        org.apache.camel.impl.health.DefaultHealthCheckRegistry registry = new org.apache.camel.impl.health.DefaultHealthCheckRegistry();

        // Add custom health checks
        registry.register(new org.apache.camel.impl.health.AbstractHealthCheck("{{serviceName}}-camel-health", "{{serviceName}}") {
            @Override
            protected void doCall(org.apache.camel.health.HealthCheckResultBuilder builder,
                                  java.util.Map<String, Object> options) {
                try {
                    // Perform health check logic
                    builder.up()
                           .detail("service", "{{serviceNameTitleCase}}")
                           .detail("status", "healthy")
                           .detail("timestamp", java.time.LocalDateTime.now());
                } catch (Exception e) {
                    builder.down()
                           .detail("service", "{{serviceNameTitleCase}}")
                           .detail("status", "unhealthy")
                           .detail("error", e.getMessage());
                }
            }
        });

        return registry;
    }
}
