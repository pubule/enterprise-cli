    /**
     * 🤖 Helper method to safely try searching a field
     */
    private jakarta.persistence.criteria.Predicate trySearchField(
            jakarta.persistence.criteria.Root<T> root,
            jakarta.persistence.criteria.CriteriaBuilder criteriaBuilder,
            String fieldName,
            String likePattern) {
        try {
            return criteriaBuilder.like(
                criteriaBuilder.lower(root.get(fieldName).as(String.class)),
                likePattern
            );
        } catch (Exception e) {
            // Field doesn't exist or is not searchable
            return criteriaBuilder.conjunction(); // Returns true (no effect on OR)
        }
    }

