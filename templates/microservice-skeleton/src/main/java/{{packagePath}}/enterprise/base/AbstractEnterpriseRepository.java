    /**
     * 🤖 Soft delete entity by ID
     * Sets active = false instead of physical deletion
     */
    default void softDeleteById(ID id) {
        findById(id).ifPresent(entity -> {
            try {
                // Use reflection to set active field to false
                java.lang.reflect.Field activeField = entity.getClass().getDeclaredField("active");
                activeField.setAccessible(true);
                activeField.set(entity, false);

                // Set deletion timestamp if field exists
                try {
                    java.lang.reflect.Field deletedAtField = entity.getClass().getDeclaredField("deletedAt");
                    deletedAtField.setAccessible(true);
                    deletedAtField.set(entity, LocalDateTime.now());
                } catch (NoSuchFieldException e) {
                    // deletedAt field doesn't exist, skip
                }

                save(entity);
            } catch (Exception e) {
                // Fallback to physical deletion if soft delete fails
                deleteById(id);
            }
        });
    }

    /**
     * 🤖 Restore soft deleted entity
     */
    default void restoreById(ID id) {
        findById(id).ifPresent(entity -> {
            try {
                java.lang.reflect.Field activeField = entity.getClass().getDeclaredField("active");
                activeField.setAccessible(true);
                activeField.set(entity, true);

                // Clear deletion timestamp if field exists
                try {
                    java.lang.reflect.Field deletedAtField = entity.getClass().getDeclaredField("deletedAt");
                    deletedAtField.setAccessible(true);
                    deletedAtField.set(entity, null);
                } catch (NoSuchFieldException e) {
                    // deletedAt field doesn't exist, skip
                }

                save(entity);
            } catch (Exception e) {
                // Ignore if soft delete fields don't exist
            }
        });
    }

