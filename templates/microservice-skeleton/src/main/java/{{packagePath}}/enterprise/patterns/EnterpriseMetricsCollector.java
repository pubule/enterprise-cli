    // ================================
    // 🤖 INTERNAL UTILITY METHODS
    // ================================

    private Timer getOrCreateTimer(String name, String... tags) {
        String key = name + ":" + String.join(":", tags);
        return timers.computeIfAbsent(key, k -> Timer.builder(name).tags(tags).register(meterRegistry));
    }

    private void incrementCounter(String name, String... tags) {
        String key = name + ":" + String.join(":", tags);
        counters.computeIfAbsent(key, k -> Counter.builder(name).tags(tags).register(meterRegistry))
                .increment();
    }

    /**
     * 🤖 Get current metrics summary for entity
     */
    public MetricsSummary getMetricsSummary(Class<?> entityClass) {
        String entityName = entityClass.getSimpleName().toLowerCase();

        return new MetricsSummary(
            entityName,
            getCounterValue("enterprise.service.creation.success", "entity", entityName),
            getCounterValue("enterprise.service.read.success", "entity", entityName),
            getCounterValue("enterprise.service.update.success", "entity", entityName),
            getCounterValue("enterprise.service.deletion.success", "entity", entityName),
            getCounterValue("enterprise.service.validation.error", "entity", entityName),
            getCounterValue("enterprise.service.system.error", "entity", entityName)
        );
    }

    private double getCounterValue(String name, String... tags) {
        try {
            return meterRegistry.counter(name, tags).count();
        } catch (Exception e) {
            return 0.0;
        }
    }

    /**
     * 🤖 Metrics Summary for reporting
     */
    public static class MetricsSummary {
        private final String entityName;
        private final double creations;
        private final double reads;
        private final double updates;
        private final double deletions;
        private final double validationErrors;
        private final double systemErrors;

        public MetricsSummary(String entityName, double creations, double reads, double updates,
                             double deletions, double validationErrors, double systemErrors) {
            this.entityName = entityName;
            this.creations = creations;
            this.reads = reads;
            this.updates = updates;
            this.deletions = deletions;
            this.validationErrors = validationErrors;
            this.systemErrors = systemErrors;
        }

        // Getters
        public String getEntityName() { return entityName; }
        public double getCreations() { return creations; }
        public double getReads() { return reads; }
        public double getUpdates() { return updates; }
        public double getDeletions() { return deletions; }
        public double getValidationErrors() { return validationErrors; }
        public double getSystemErrors() { return systemErrors; }
        public double getTotalOperations() { return creations + reads + updates + deletions; }
        public double getTotalErrors() { return validationErrors + systemErrors; }
        public double getErrorRate() {
            double total = getTotalOperations();
            return total > 0 ? (getTotalErrors() / total) * 100 : 0;
        }

        @Override
        public String toString() {
            return String.format("MetricsSummary{entity='%s', operations=%.0f, errors=%.0f, errorRate=%.2f%%}",
                                entityName, getTotalOperations(), getTotalErrors(), getErrorRate());
        }
    }
